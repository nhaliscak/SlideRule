"""Write docs/COVERAGE.md: every discipline and sub-discipline from the taxonomy with the calculations that serve it.

    python scripts/coverage_report.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from sliderule.core.catalog import default_catalog  # noqa: E402
from sliderule.core.taxonomy import TAXONOMY  # noqa: E402


def main() -> None:
    cat = default_catalog()
    by_sub: dict[str, list] = {}
    by_disc: dict[str, int] = {}
    for c in cat:
        for s in c.subdisciplines:
            by_sub.setdefault(s, []).append(c)
        for d in c.disciplines:
            by_disc[d] = by_disc.get(d, 0) + 1
    lines = [
        "# Coverage: disciplines, sub-disciplines and calculations",
        "",
        "Generated by `scripts/coverage_report.py` from the taxonomy in `src/sliderule/core/taxonomy.py`, which a test keeps identical to "
        "`docs/reference/disciplines.txt`. Another test fails if any sub-discipline in that file has no calculation.",
        "",
        f"**{len(cat)} calculations** · {len(TAXONOMY)} disciplines · {len(by_sub)} sub-disciplines",
        "",
    ]
    for group, title in (("core", "Core disciplines"), ("emerging", "Emerging and interdisciplinary fields")):
        lines += [f"## {title}", ""]
        for did, (name, g, subs) in TAXONOMY.items():
            if g != group:
                continue
            lines += [f"### {name} (`{did}`) — {by_disc.get(did, 0)} calculations", ""]
            for s in subs:
                calcs = by_sub.get(s, [])
                names = "; ".join(f"[{c.name}](`{c.id}`)" for c in sorted(calcs, key=lambda c: c.name)[:6])
                more = f" … (+{len(calcs) - 6} more)" if len(calcs) > 6 else ""
                lines.append(f"- **{s}** ({len(calcs)}): {names}{more}")
            lines.append("")
    (ROOT / "docs" / "COVERAGE.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote docs/COVERAGE.md ({len(cat)} calculations)")


if __name__ == "__main__":
    main()
