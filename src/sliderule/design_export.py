def export_system(graph: dict, fmt: str = "latex", mode: str = "both", sig_figs: int = 5, standalone: bool = True, title: str = "System model") -> dict:
    """Render the system as ``fmt`` ("latex" | "markdown"). ``ok`` is false (with diagnostics) if the system cannot be evaluated."""
    if fmt not in FORMATS:
        return {"ok": False, "diagnostics": [{"level": "error", "code": "BAD_FORMAT", "message": f"format must be one of {', '.join(FORMATS)}", "block": None}]}
    if mode not in MODES:
        return {"ok": False, "diagnostics": [{"level": "error", "code": "BAD_MODE", "message": f"mode must be one of {', '.join(MODES)}", "block": None}]}
    problems = validate_graph(graph or {})
    if problems or not (graph or {}).get("blocks"):
        return {"ok": False, "diagnostics": problems or [{"level": "error", "code": "EMPTY", "message": "the system has no blocks", "block": None}]}
    if fmt == "python":
        numeric_blocks = [b["id"] for b in (graph or {}).get("blocks", []) if _has_numeric_ode(b.get("calc"))]
        if numeric_blocks:
            return {"ok": False, "diagnostics": [{"level": "error", "code": "NUMERIC_ODE", "block": numeric_blocks[0], "message":
                    "the Python script export cannot represent this differential equation (block "
                    f"{numeric_blocks[0]}): it is solved numerically in a way that has no standalone script (fractional or stochastic equations, "
                    "conservation laws with shocks, moving boundaries, cutouts, interior boundary conditions); export LaTeX, Markdown or HTML instead, or use the solver"}]}
        content, diags = render_python(graph, sig_figs, title)
        if not content:
            return {"ok": False, "diagnostics": diags}
        return {"ok": True, "format": fmt, "mode": "both", "filename": "sliderule-system.py", "mime": "text/x-python", "content": content, "diagnostics": diags}
    if fmt in ("matlab", "excel"):
        from . import design_code

        if fmt == "matlab":
            content, diags = design_code.render_matlab(graph, sig_figs, title)
            if not content:
                return {"ok": False, "diagnostics": diags}
            return {"ok": True, "format": fmt, "mode": "both", "filename": "sliderule-system.m", "mime": "text/x-matlab", "content": content, "diagnostics": diags}
        blob, diags = design_code.render_excel(graph, sig_figs, title)
        if not blob:
            return {"ok": False, "diagnostics": diags}
        import base64

        return {"ok": True, "format": fmt, "mode": "both", "filename": "sliderule-system.xlsx", "binary": True, "content_base64": base64.b64encode(blob).decode("ascii"),
                "mime": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "diagnostics": diags}
    doc, diags = build_document(graph, mode, sig_figs, title)
    if not doc:
        return {"ok": False, "diagnostics": diags}
    if fmt == "latex":
        content, ext, mime = render_latex(doc, title, standalone), "tex", "application/x-tex"
    elif fmt == "html":
        content, ext, mime = render_html(doc, title), "html", "text/html"
    else:
        content, ext, mime = render_markdown(doc, title), "md", "text/markdown"
    suffix = "" if mode == "both" else f"-{mode}"
    return {"ok": True, "format": fmt, "mode": mode, "filename": f"sliderule-system{suffix}.{ext}", "mime": mime, "content": content, "diagnostics": diags}
