"""Export a System Design graph as a document: LaTeX or Markdown, symbolic and/or numeric.

The document lists the *complete system of equations* (every block's equations with block-qualified symbols plus
one equality per wire), the chosen unknowns, a closed-form expression for every output in terms of the system's free
inputs (where the equations chain explicitly), and each block's worked solution. All maths is generated by the same
code that evaluates the system, so what is printed is what was computed. No language model is involved.

Model first, rendering second: :func:`build_document` produces a small list of blocks (headings, paragraphs, display
maths, tables) and the two renderers turn it into LaTeX or Markdown.
"""

