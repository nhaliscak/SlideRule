def render_latex(doc: list, title: str, standalone: bool = True) -> str:
    out: list[str] = []
    if standalone:
        out += [_TEX_PREAMBLE, rf"\title{{{tex_text(title)}}}", r"\date{}", r"\begin{document}", r"\maketitle", ""]
    sec = {2: r"\section", 3: r"\subsection", 4: r"\subsubsection"}
    for item in doc:
        if isinstance(item, Heading):
            if item.level == 1:
                continue   # the title
            out += ["", f"{sec.get(item.level, chr(92) + 'paragraph')}{{{tex_text(item.text)}}}"]
        elif isinstance(item, Para):
            out += ["", _tex_parts(item.parts)]
        elif isinstance(item, Display):
            tag = rf"\tag*{{\small\textit{{{tex_text(item.note)}}}}}" if item.note else ""
            out += [r"\[", item.tex + (" " + tag if tag else ""), r"\]"]
        elif isinstance(item, Table):
            cols = "l" * len(item.header)
            out += ["", r"\begin{center}", rf"\begin{{tabular}}{{{cols}}}", r"\toprule",
                    " & ".join(tex_text(h) for h in item.header) + r" \\", r"\midrule"]
            for row in item.rows:
                out.append(" & ".join(_tex_parts([c]) for c in row) + r" \\")
            out += [r"\bottomrule", r"\end{tabular}", r"\end{center}"]
    if standalone:
        out += ["", r"\end{document}", ""]
    return "\n".join(out)


def md_text(s: str) -> str:
    """Escape plain text for Markdown (units such as J/(kg*K) must not start emphasis)."""
    return re.sub(r"([\\`*_$|<>])", r"\\\1", str(s)).replace("\n", " ")


def _md_parts(parts: list) -> str:
    return "".join(f"${p.tex}$" if isinstance(p, M) else md_text(p) for p in parts)


def render_markdown(doc: list, title: str) -> str:
    out: list[str] = []
    for item in doc:
        if isinstance(item, Heading):
            out += ["", "#" * item.level + " " + md_text(item.text), ""]
        elif isinstance(item, Para):
            out += [_md_parts(item.parts), ""]
        elif isinstance(item, Display):
            out += ["$$", item.tex, "$$"] + ([f"*{md_text(item.note)}*"] if item.note else []) + [""]
        elif isinstance(item, Table):
            out += ["| " + " | ".join(_md_parts([h]) for h in item.header) + " |", "|" + "|".join(" --- " for _ in item.header) + "|"]
            out += ["| " + " | ".join(_md_parts([c]) for c in row) + " |" for row in item.rows]
            out.append("")
    text = "\n".join(out)
    return re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"


