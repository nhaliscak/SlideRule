def _display_name(calc) -> str:
    return calc.name + (" (user-defined)" if calc.custom else "")


def build_document(graph: dict, mode: str = "both", sig_figs: int = 5, title: str = "System model") -> tuple[list, list[dict]]:
    """Return ``(document, diagnostics)``; the document is empty when the system cannot be evaluated."""
    result = solve_system(graph, sig_figs)
    if not result["ok"]:
        return [], result["diagnostics"]
    model = system_model(graph)
    blocks, order, names = model["blocks"], model["order"], model["names"]
    symbolic = mode in ("both", "symbolic")
    numeric = mode in ("both", "numeric")
    reg = default_registry()
    doc: list = [Heading(1, title)]
    doc.append(Para([
        f"Generated by SlideRule {__version__}. Every symbol carries a superscript naming its block: ",
        M(r"{x}^{(\mathrm{b1})}"), " is variable ", M("x"), " of block b1. Inside each block's worked solution the "
        "symbols are local to that block. Computation is done in coherent SI units; values are converted at the wires. "
        "All results come from deterministic code (no language model)."]))

    # ---- 1. overview
    doc.append(Heading(2, "System overview"))
    doc.append(Table(["Block", "Calculation", "Order"], [
        [bid, _display_name(blocks[bid]["_calc"]), str(i + 1)] for i, bid in enumerate(order)]))
    if any(blocks[b]["_calc"].custom for b in order):
        doc.append(Para(["Blocks marked user-defined use equations entered by a user rather than the vetted SlideRule library. "
                         "Their units are checked for consistency, but their physics is the author's responsibility."]))
    for bid in order:
        b = blocks[bid]
        calc, roles = b["_calc"], b["_roles"]
        doc.append(Heading(3, f"Block {bid}: {_display_name(calc)}"))
        if (b.get("comment") or "").strip():
            doc.append(Para(["Comment: ", b["comment"].strip()]))
        rows = []
        for v in calc.variables:
            role = roles[v.key]
            src = model["drivers"].get((bid, v.key)) if role == "input" else None
            if v.is_constant:
                what = f"{v.constant:g}" + ("" if v.unit in ("", "1") else f" {v.unit}") + " (physical constant)"
            elif role == "output":
                what = "computed"
            elif src:
                what = f"wire from {src[0]}.{src[1]}"
            else:
                what = _cell_value(b, v, sig_figs)
            kind = "temperature difference" if v.delta else reg.describe(v.dim)
            rows.append([M(v.latex), v.label, role, what, f"{kind} [{v.si}]" if kind != v.si else f"[{v.si}]"])
        doc.append(Table(["Symbol", "Variable", "Role", "Value / source", "Type [SI unit]"], rows))

    # ---- 2. complete system of equations
    if symbolic:
        doc.append(Heading(2, "Complete system of equations"))
        doc.append(Para(["Each block contributes its governing equations (written with block-qualified symbols); each wire adds an equality. "
                         "Quantities marked as inputs or constants are known; outputs are the unknowns."]))
        for bid in order:
            doc.append(Heading(3, f"Block {bid}: {blocks[bid]['_calc'].name}"))
            shown_odes: set[int] = set()
            for (eq, lhs, rhs, needed) in model["equations"][bid]:
                note = eq.title + ("" if needed else " (not needed for the chosen outputs)")
                if eq.ode is not None and id(eq.ode) not in shown_odes:
                    shown_odes.add(id(eq.ode))
                    m = {v.symbol: model["qsym"][(bid, v.key)] for v in blocks[bid]["_calc"].variables}
                    for a, b in eq.ode.written:
                        doc.append(Display(f"{_tex(a.xreplace(m), names)} = {_tex(b.xreplace(m), names)}", f"{eq.ode.title} — differential equation, as written"))
                    if getattr(eq.ode, "pde", False):
                        for a, b, note in eq.ode.export_conditions():
                            doc.append(Display(f"{_tex(a.xreplace(m), names)} = {_tex(b.xreplace(m), names)}", f"{eq.ode.title} — {'initial' if note == 'initial' else 'boundary'} condition ({note})"))
                    elif eq.ode.bvp is not None:
                        for pos, _res, written in eq.ode.bvp.conditions:
                            if written is not None:
                                doc.append(Display(f"{_tex(written[0].xreplace(m), names)} = {_tex(written[1].xreplace(m), names)}",
                                                   f"{eq.ode.title} — boundary condition at {eq.ode.t.name} = {pos}"))
                    else:
                        for (dep, j), idx in eq.ode.state_index.items():
                            lhs_tex = f"{{{_tex(m[dep], names)}}}" + (f"^{{({j})}}" if j else "") + f"\\left({_tex(eq.ode.start.xreplace(m), names)}\\right)"
                            doc.append(Display(f"{lhs_tex} = {_tex(eq.ode.ics[idx].xreplace(m), names)}", f"{eq.ode.title} — initial condition"))
                    if eq.ode.numeric:
                        doc.append(Para([f"The differential equation “{eq.ode.title}” has no closed-form solution; it is integrated numerically, and its solution is written ",
                                         M(r"y_{\mathrm{ODE}}(\ldots)"), " below."]))
                if eq.written:   # derivatives/integrals: show the equation as entered, then the evaluated algebra the system uses
                    m = {v.symbol: model["qsym"][(bid, v.key)] for v in blocks[bid]["_calc"].variables}
                    wl, wr = (side.xreplace(m) for side in eq.written)
                    doc.append(Display(f"{_tex(wl, names)} = {_tex(wr, names)}", note + " — as written"))
                    note += " — derivatives and integrals evaluated"
                doc.append(Display(f"{_tex(lhs, names)} = {_tex(rhs, names)}", note))
        if model["wires"]:
            doc.append(Heading(3, "Wire equations"))
            doc.append(Para(["A wire sets the input equal to the connected output (after conversion to a common unit)."]))
            for w in model["wires"]:
                dst = model["qsym"][(w["to"]["block"], w["to"]["key"])]
                src = model["qsym"][(w["from"]["block"], w["from"]["key"])]
                doc.append(Display(f"{_tex(dst, names)} = {_tex(src, names)}"))

        # ---- 3. closed forms
        doc.append(Heading(2, "Closed-form outputs in terms of the system inputs"))
        doc.append(Para(["All quantities here are in coherent SI units. Wired inputs have been eliminated by substituting the upstream expressions."]))
        for bid in order:
            outs = [k for k, r in blocks[bid]["_roles"].items() if r == "output"]
            for k in outs:
                expr = model["closed"].get((bid, k))
                if expr is None:
                    continue
                v = blocks[bid]["_calc"].by_key[k]
                lhs = _tex(model["qsym"][(bid, k)], names)
                if sp.count_ops(expr) > 600:
                    doc.append(Para([M(lhs), f": expression too long to print ({int(sp.count_ops(expr))} operations); see the block steps."]))
                else:
                    doc.append(Display(f"{lhs} = {_tex(expr, names)}", f"{v.label} [{v.si}]"))
        free_rows = []
        for (bid, key), v in model["free"].items():
            free_rows.append([M(_tex(model["qsym"][(bid, key)], names)), f"{v.label} (block {bid})", v.si])
        if free_rows:
            doc.append(Heading(3, "Free inputs and constants"))
            doc.append(Table(["Symbol", "Meaning", "SI unit"], free_rows))

    # ---- 4. worked solutions
    doc.append(Heading(2, "Worked solutions"))
    for bid in order:
        sol = result["blocks"][bid]
        doc.append(Heading(3, f"Block {bid}: {blocks[bid]['_calc'].name}"))
        incoming = [(w, blocks) for w in model["wires"] if w["to"]["block"] == bid]
        if numeric and incoming:
            doc.append(Para(["Values received on wires (carried in SI, shown here in the receiving input's unit):"]))
            for w, _ in incoming:
                up = result["blocks"][w["from"]["block"]]
                o = next(o for o in up["outputs"] if o["key"] == w["from"]["key"])
                dv = blocks[bid]["_calc"].by_key[w["to"]["key"]]
                dst_unit = reg.parse(dv.unit, as_delta=dv.delta)
                shown = dst_unit.from_si(o["si_value"])
                dsym = names[model["qsym"][(bid, w["to"]["key"])]]
                ssym = names[model["qsym"][(w["from"]["block"], w["from"]["key"])]]
                doc.append(Display(
                    f"{dsym} = {ssym} = {quantity_tex(o['si_value'], dv.si_parsed, sig_figs)} = {quantity_tex(shown, dst_unit, sig_figs)}"))
        for kind, want in (("symbolic", symbolic), ("numeric", numeric)):
            if not want:
                continue
            if mode == "both":
                doc.append(Heading(4, "Symbolic solution" if kind == "symbolic" else "Numeric solution"))
            for st in sol["steps"][kind]:
                doc.append(Para([M(r"\blacktriangleright"), " ", st["title"]]))
                for line in st["lines"]:
                    doc.append(Display(line["latex"], line["note"]))
    if numeric:
        doc.append(Heading(2, "Results"))
        rows = []
        for bid in order:
            for o in result["blocks"][bid]["outputs"]:
                rows.append([bid, M(o["latex"]), o["label"], f"{o['value_text']}", M(o["unit_latex"]) if o["unit_latex"] else "—"])
        doc.append(Table(["Block", "Symbol", "Quantity", "Value", "Unit"], rows))
    notes = [d for d in result["diagnostics"] if d["level"] != "info"]
    if notes:
        doc.append(Heading(2, "Notes and warnings"))
        for d in notes:
            doc.append(Para([f"[{d['level']}] block {d['block']}: {d['message']}"]))
    return doc, result["diagnostics"]


