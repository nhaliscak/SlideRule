def _html_parts(parts: list) -> str:
    return "".join(f'<span class="tex pending">{html.escape(p.tex, quote=False)}</span>' if isinstance(p, M) else html.escape(str(p), quote=False) for p in parts)


def render_html(doc: list, title: str) -> str:
    """Printable page; math is typeset in the browser by KaTeX, embedded in the file (CDN links if the bundled copy is missing)."""
    v = _katex_tags()
    out = [(_HTML_HEAD % {**v, "title": html.escape(title)}), f"<h1>{html.escape(title)}</h1>"]
    for item in doc:
        if isinstance(item, Heading):
            if item.level == 1:
                continue
            out.append(f"<h{item.level}>{html.escape(item.text, quote=False)}</h{item.level}>")
        elif isinstance(item, Para):
            out.append(f"<p>{_html_parts(item.parts)}</p>")
        elif isinstance(item, Display):
            note = f'<span class="note">{html.escape(item.note, quote=False)}</span>' if item.note else ""
            out.append(f'<div class="eq"><span class="tex pending" data-display="1">{html.escape(item.tex, quote=False)}</span>{note}</div>')
        elif isinstance(item, Table):
            out.append("<table><thead><tr>" + "".join(f"<th>{_html_parts([h])}</th>" for h in item.header) + "</tr></thead><tbody>")
            out += ["<tr>" + "".join(f"<td>{_html_parts([c])}</td>" for c in row) + "</tr>" for row in item.rows]
            out.append("</tbody></table>")
    out.append(_HTML_TAIL % v)
    return "\n".join(out)


_PY_HEAD = '''#!/usr/bin/env python3
"""%(title)s

Generated by SlideRule %(version)s. Reproduces the whole system with SymPy: every symbol is block-qualified
(``name__block``), all values are coherent SI, and each output has a closed-form expression that already
includes the wires. Run it to print the results; import it and call ``evaluate({...})`` to try other inputs.
Requires: sympy
"""
import sympy as sp

NS: dict = {"log10": lambda x: sp.log(x, 10), "log2": lambda x: sp.log(x, 2)}   # SlideRule's fixed-base logs


def sym(name, signed=False):
    NS[name] = sp.Symbol(name, real=True) if signed else sp.Symbol(name, positive=True)
    return NS[name]


def E(text):
    """Parse an expression written in the block-qualified symbols."""
    return sp.sympify(text, locals=NS)


def to_si(value, factor, shift=0.0):
    """Unit standardization: SI = (value + shift) * factor."""
    return (value + shift) * factor
'''


def _py_name(bid: str, key: str, used: dict) -> str:
    base = re.sub(r"\W", "_", f"{key}__{bid}")
    name, n = base, 2
    while name in used.values():
        name, n = f"{base}_{n}", n + 1
    return name


def _py_comment(text) -> list[str]:
    """A block's comment as Python comment lines (every line prefixed; other control and line-separator characters become spaces so nothing can end the comment)."""
    lines = [ln.rstrip() for ln in str(text or "").replace("\r\n", "\n").replace("\r", "\n").split("\n")]
    lines = ["".join(ch if ch.isprintable() else " " for ch in ln).rstrip() for ln in lines]
    while lines and not lines[-1]:
        lines.pop()
    return [f"#   {ln}".rstrip() for ln in lines]


def render_python(graph: dict, sig_figs: int = 5, title: str = "System model") -> tuple[str, list[dict]]:
    """A standalone SymPy script reproducing the system (equations, closed forms, inputs in SI, expected results)."""
    result = solve_system(graph, sig_figs)
    if not result["ok"]:
        return "", result["diagnostics"]
    from .core.engine import parse_quantity

    model = system_model(graph)
    blocks, order, qsym = model["blocks"], model["order"], model["qsym"]
    reg = default_registry()
    pyname: dict = {}
    for bid in order:
        for v in blocks[bid]["_calc"].variables:
            pyname[(bid, v.key)] = _py_name(bid, v.key, pyname)
    rename = {qsym[k]: (sp.Symbol(n, real=True) if blocks[k[0]]["_calc"].by_key[k[1]].signed else sp.Symbol(n, positive=True)) for k, n in pyname.items()}

    ode_fns: dict = {}      # (system id, class name) -> (script name, system, dependent symbol): plain initial-value problems the script integrates itself
    sys_fns: dict = {}      # (system id, class name) -> (script name, system, kind, role): events, delays, boundary-value problems and PDEs

    def _scan(expr) -> None:
        for a in expr.atoms(sp.Function):
            system = getattr(type(a), "_sliderule_ode", None)
            if system is None or (id(system), type(a).__name__) in ode_fns or (id(system), type(a).__name__) in sys_fns:
                continue
            kind = _export_kind(system) if system.numeric else None
            if kind == "ivp" and getattr(type(a), "_sliderule_plain", False) and not system.events and not any(sp.denom(sp.together(r)).has(system.t) for r in system.rhs):
                dep = type(a)._sliderule_dep
                ode_fns[(id(system), type(a).__name__)] = (f"ODE{len(ode_fns) + 1}_{dep.name}", system, dep)
            elif kind is not None:
                dep = getattr(type(a), "_sliderule_dep", None)
                sys_fns[(id(system), type(a).__name__)] = (f"SYS{len(sys_fns) + 1}_{dep.name if dep is not None else 'r'}", system, kind, _node_role(type(a), system, kind))

    for bid in order:
        for (_e, lhs_, rhs_, _n) in model["equations"][bid]:
            _scan(lhs_)
            _scan(rhs_)
    for expr_ in model["closed"].values():
        _scan(expr_)

    def code(expr) -> str:
        if ode_fns or sys_fns:
            key_of = lambda e: (id(getattr(type(e), "_sliderule_ode", None)), type(e).__name__)             # noqa: E731
            expr = expr.replace(lambda e: isinstance(e, sp.Function) and (key_of(e) in ode_fns or key_of(e) in sys_fns),
                                lambda e: sp.Function((ode_fns.get(key_of(e)) or sys_fns[key_of(e)])[0])(*e.args))
        return repr(sp.sstr(expr.xreplace(rename)))

    out = [_PY_HEAD % {"title": title, "version": __version__}, "", "# ---- inputs and constants (given value, unit conversion to SI)"]
    out += [f"sym({pyname[k]!r}{', True' if v.signed else ''})" for k, v in model["free"].items()]
    for (bid, key), v in model["free"].items():
        text = (blocks[bid].get("values") or {}).get(key)
        val, unit = parse_quantity(text) if text else (v.default if v.default is not None else v.constant, v.unit)
        unit = (unit or v.unit).strip()
        u = reg.parse(unit, as_delta=v.delta)
        kind = "constant" if v.is_constant else "input"
        out.append(f"{pyname[(bid, key)]} = to_si({val!r}, {u.factor!r}, {u.shift!r})   # block {bid}: {v.label} ({kind}), {fmt_number(val, sig_figs)[0]}{'' if unit in ('', '1') else ' ' + unit} -> SI {v.si}")
    out.append("INPUTS = {" + ", ".join(f"NS[{pyname[k]!r}]: {pyname[k]}" for k in model["free"]) + "}")

    if any(name in line for line in out for name in ("besselj_zero", "eig_slab", "eig_cylinder", "eig_sphere")) or any(
            name in code(lhs) + code(rhs) for bid in order for (_e, lhs, rhs, _n) in model["equations"][bid] for name in ("besselj_zero", "eig_slab", "eig_cylinder", "eig_sphere")):
        from .core.special import script_support

        out[0] = out[0].replace("Requires: sympy", "Requires: sympy, scipy")
        out += ["", "# ---- SlideRule's Bessel-zero and transient-conduction eigenvalue helpers", script_support()]
    tabs = {(t["name"], tuple(t["x"]), tuple(t["y"]), t.get("method", "linear"), t.get("outside", "error")): None for bid in order for t in blocks[bid]["_calc"].tables}
    if tabs:
        from .core import tables as _tables

        si = []
        for bid in order:
            for fn in {f for eq in blocks[bid]["_calc"].parsed for side in (eq.lhs, eq.rhs) for f in side.atoms(sp.Function) if hasattr(f.func, "_sliderule_table")}:
                nm, xs, ys, method, outside = fn.func._sliderule_table
                si.append((fn.func.__name__, xs, ys, method, outside))
        if si:
            out[0] = out[0].replace("Requires: sympy", "Requires: sympy, numpy, scipy")
            out += ["", "# ---- tabulated data (SI numbers) as functions: interpolated and differentiable", _tables.script_support(list(dict.fromkeys(si)))]
    if ode_fns:
        out[0] = out[0].replace("Requires: sympy", "Requires: sympy, scipy")
        out += ["", "# ---- differential equations solved numerically: integrated again here with SciPy (agreement is to the solver tolerance)", _ODE_SUPPORT]
        for newname, system, dep in ode_fns.values():
            ins = [x.name for x in system.inputs]
            out.append(f"NS[{newname!r}] = _ode({newname!r}, {ins!r}, {[x.name for x in system.state]!r}, {[sp.sstr(r) for r in system.rhs]!r}, "
                       f"{[sp.sstr(c) for c in system.ics]!r}, {sp.sstr(system.start)!r}, {system.state_index[(dep, 0)]}, {system.t.name!r})")
    if sys_fns:
        from .export_support import SYSTEM_SUPPORT

        out[0] = out[0].replace("Requires: sympy", "Requires: sympy, numpy, scipy")
        out += ["", "# ---- events, delays, boundary-value problems and partial differential equations: solved again here with SciPy (agreement is to the solver tolerance)", SYSTEM_SUPPORT]
        if any(v[2] == "pde" for v in sys_fns.values()):
            from .export_pde import PDE_SUPPORT

            out += ["", PDE_SUPPORT]
        specs: dict = {}
        for newname, system, kind, role in sys_fns.values():
            sk = id(system)
            if sk not in specs:
                specs[sk] = f"SPEC{len(specs) + 1}"
                out.append(f"{specs[sk]} = {_system_spec(system, kind)!r}")
            out.append(f"NS[{newname!r}] = _system({newname!r}, {specs[sk]}, {role!r})")
    out += ["", "# ---- the equations of every block (block-qualified symbols)"]
    for bid in order:
        calc = blocks[bid]["_calc"]
        out.append(f"# block {bid}: {_display_name(calc)}")
        out += _py_comment(blocks[bid].get("comment"))
        for v in calc.variables:
            if (bid, v.key) not in model["free"]:
                out.append(f"sym({pyname[(bid, v.key)]!r}{', True' if v.signed else ''})")
        for i, (eq, lhs, rhs, needed) in enumerate(model["equations"][bid], 1):
            out.append(f"eq_{re.sub(chr(92) + 'W', '_', bid)}_{i} = sp.Eq(E({code(lhs)}), E({code(rhs)}))   # {eq.title}" + (f" (written: {eq.text})" if eq.written else "") + ("" if needed else " (not needed for the chosen outputs)"))

    out += ["", "# ---- closed-form outputs (wires already substituted)"]
    table = []
    for bid in order:
        for o in result["blocks"][bid]["outputs"]:
            key = o["key"]
            expr = model["closed"].get((bid, key))
            if expr is None:
                continue
            v = blocks[bid]["_calc"].by_key[key]
            n = pyname[(bid, key)]
            u = reg.parse(o["unit"], as_delta=v.delta)
            out.append(f"{n} = E({code(expr)})   # {v.label}, SI {v.si}")
            table.append((n, f"{bid}: {v.label}", o["unit"], u.factor, u.shift, o["si_value"]))

    tol = 1e-3 if any(v[2] == "pde" for v in sys_fns.values()) else (1e-4 if ode_fns or sys_fns else 1e-6)
    out += ["", f"TOLERANCE = {tol!r}   # relative agreement with SlideRule's values" + ("; looser because differential equations are integrated numerically" if ode_fns or sys_fns else ""),
            "OUTPUTS = [   # (symbol, label, display unit, unit factor, unit shift, SlideRule reference value in SI)"]
    out += [f"    ({n!r}, {lab!r}, {un!r}, {f!r}, {sh!r}, {ref!r})," for n, lab, un, f, sh, ref in table]
    out += ["]", ""]
    if ode_fns or sys_fns:       # a quantity that is zero by construction (the height at touchdown) is only zero to the solver's accuracy
        out += ["FLOOR = 1e-9 * max([abs(o[5]) for o in OUTPUTS] + [1e-300])   # absolute floor for outputs that are zero to the solver's accuracy", ""]
    else:
        out += ["FLOOR = 0.0", ""]
    out.append('''
def evaluate(overrides=None):
    """Numeric SI value of each output; ``overrides`` maps input names (e.g. "h__b1") to SI values."""
    values = dict(INPUTS)
    for name, val in (overrides or {}).items():
        values[NS[name]] = val
    return {name: float(globals()[name].subs(values)) for name, *_ in OUTPUTS}


if __name__ == "__main__":
    got = evaluate()
    ok = True
    for name, label, unit, factor, shift, ref in OUTPUTS:
        si = got[name]
        print(f"{label:<48} {si / factor - shift:>14.6g} {unit}   (SI {si:.6g})")
        ok &= abs(si - ref) <= TOLERANCE * max(abs(ref), 1e-300) + FLOOR
    print("matches the SlideRule reference values" if ok else "DIFFERS from the SlideRule reference values")
''')
    return "\n".join(out) + "\n", result["diagnostics"]


